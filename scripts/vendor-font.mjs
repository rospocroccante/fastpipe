// Inlines the dashboard's two faces as base64 data URIs, so the dashboard works offline
// and ships in the single-file npm package. Both SIL Open Font License 1.1.
//   Inter 4, variable weight and optical size (Inter Display at headline sizes), latin:
//     @fontsource-variable/inter 5.3.0, files/inter-latin-opsz-normal.woff2
//   JetBrains Mono, variable weight, latin:
//     @fontsource-variable/jetbrains-mono, files/jetbrains-mono-latin-wght-normal.woff2
// usage: node scripts/vendor-font.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const b64 = (f) => fs.readFileSync(path.join(root, 'assets/fonts', f)).toString('base64');
const out = path.join(root, 'src/dashboard/font.ts');
fs.writeFileSync(
  out,
  '// GENERATED by scripts/vendor-font.mjs - do not edit by hand.\n' +
    '// Inter 4 (weight and optical size) and JetBrains Mono (weight), latin subsets, SIL Open Font License 1.1:\n' +
    '// assets/INTER_LICENSE.txt and assets/JETBRAINS_MONO_LICENSE.txt.\n\n' +
    `export const INTER_WOFF2 = 'data:font/woff2;base64,${b64('inter-latin-opsz-normal.woff2')}';\n` +
    `export const MONO_WOFF2 = 'data:font/woff2;base64,${b64('jetbrains-mono-latin-wght-normal.woff2')}';\n`,
);
console.log(`wrote ${path.relative(root, out)}`);
